class Pair<T1, T2> {
  final T1 a;
  final T2 b;

  Pair(this.a, this.b);
}

class Triple<T1, T2, T3> {
  final T1 a;
  final T2 b;
  final T3 c;

  Triple(this.a, this.b, this.c);
}

class Quadruple<T1, T2, T3, T4> {
  final T1 a;
  final T2 b;
  final T3 c;
  final T4 d;

  Quadruple(this.a, this.b, this.c, this.d);
}

class Quintuple<T1, T2, T3, T4, T5> {
  final T1 a;
  final T2 b;
  final T3 c;
  final T4 d;
  final T5 e;

  Quintuple(this.a, this.b, this.c, this.d, this.e);
}

class Sixtuple<T1, T2, T3, T4, T5, T6> {
  final T1 a;
  final T2 b;
  final T3 c;
  final T4 d;
  final T5 e;
  final T6 f;

  Sixtuple(this.a, this.b, this.c, this.d, this.e, this.f);
}
