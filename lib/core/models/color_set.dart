import 'package:flutter/material.dart';

class ColorSet {
  final Color mainText;
  final Color minorText;
  final Color subtext;
  final Color mainBackground;
  final Color minorBackground;
  final Color mainDetails;
  final Color minorDetails;
  final Color shadow;
  final Color accent;
  final Color primary;
  final Color dark;
  final Color error;
  final Color disabledText;
  final Color disabledBackground;
  final Color disabledPrimary;
  final Color textOnPrimary;
  final Color textOnAccent;
  final Color textOnDark;
  final Color textOnError;

  const ColorSet({
    required this.mainText,
    required this.minorText,
    required this.subtext,
    required this.mainBackground,
    required this.minorBackground,
    required this.mainDetails,
    required this.minorDetails,
    required this.shadow,
    required this.accent,
    required this.primary,
    required this.dark,
    required this.error,
    required this.disabledText,
    required this.disabledBackground,
    required this.disabledPrimary,
    required this.textOnPrimary,
    required this.textOnAccent,
    required this.textOnDark,
    required this.textOnError,
  });
}
